export function computeCategorySummary(items: CategoryItem[]) {
  return {
    total: items.length,
    active: items.filter((c) => c.status === 'active').length,
    withMerchants: items.filter((c) => c.merchantsCount > 0).length,
    empty: items.filter((c) => c.merchantsCount === 0).length,
  }
}
